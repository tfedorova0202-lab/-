    fun findAnswer(query: String): String? {
        val lowerQuery = query.lowercase()
        var bestMatch: Faq? = null
        var maxScore = 0
        
        for (faq in faqs) {
            var score = 0
            for (keyword in faq.keywords) {
                if (lowerQuery.contains(keyword)) {
                    score++
                }
            }
            if (score > maxScore) {
                maxScore = score
                bestMatch = faq
            }
        }
        
        return bestMatch?.answer
    }
