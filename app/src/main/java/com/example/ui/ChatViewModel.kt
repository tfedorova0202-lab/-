    private fun buildMfoCheckReport(result: MfoCheckResult): String {
        val entry = result.entry
        val sb = StringBuilder()
        sb.append("ОФИЦИАЛЬНАЯ ПРОВЕРКА В ГОСРЕЕСТРЕ ЦБ РФ\n")
        sb.append("Статус на момент запроса (${result.formattedCheckTime}):\n\n")
        sb.append("Результат: ${result.title}\n")
        sb.append("${result.statusExplanation}\n\n")
        
        if (entry != null) {
            sb.append("Данные реестра Банка России:\n")
            sb.append("• Полное наименование: ${entry.fullName}\n")
            sb.append("• Бренд: ${entry.brandName}\n")
            sb.append("• Тип: ${entry.mfoType} | Рег. номер ЦБ РФ: ${entry.regNumber}\n")
            sb.append("• ИНН: ${entry.inn} | ОГРН: ${entry.ogrn}\n")
            sb.append("• Дата внесения в реестр: ${entry.entryDate}\n")
            if (entry.exclusionDate != null) {
                sb.append("• ДАТА ИСКЛЮЧЕНИЯ ИЗ РЕЕСТРА: ${entry.exclusionDate}\n")
            }
            sb.append("• Официальный сайт: ${entry.officialDomains.joinToString(", ")}\n\n")
        }
        
        sb.append("Законные ограничения и гарантии (ФЗ № 353-ФЗ):\n")
        sb.append("• Предельная ставка: ${result.maxDailyRate}\n")
        sb.append("• Лимит переплаты: ${result.maxOverpaymentLimit}\n")
        sb.append("• Нормативная база: ${result.legalBasis}\n\n")
        
        sb.append("Рекомендации правового защитника:\n")
        result.recommendations.forEach { sb.append("• $it\n") }
        
        sb.append("\nРекомендованные команды:\n")
        sb.append("• /ПЛАН_ФАКТ — рассчитать законный срез переплат\n")
        sb.append("• /АНТИКОЛЛЕКТОР — отозвать согласие на звонки близким\n")
        sb.append("• /ПРОЦЕСС_ДОКУМЕНТ — подготовить возражения или жалобу в ЦБ РФ")
        
        return sb.toString()
    }
