                            currentRole = msgRole
                            currentText = java.lang.StringBuilder(msg.text)
                        }
                    }
                    if (currentText.isNotEmpty()) {
                        mergedList.add(Content(role = currentRole, parts = listOf(Part(text = currentText.toString()))))
